/** Copy the DSH primitive styles, changing only class names for the plugin's existing markup. */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const primitives = resolve(root, '../deepseek-harness/packages/client/ui-primitives/src')
const copies = [
  ['Button', { button: 'dt-btn', md: 'dt-btn-md', sm: 'dt-btn-sm', primary: 'dt-btn-primary', ghost: 'dt-btn-ghost', outline: 'dt-btn-outline', toolbar: 'dt-btn-toolbar', icon: 'dt-btn-icon' }],
  ['Input', { wrap: 'dt-input', icon: 'dt-input-icon', input: 'dt-input input' }],
  ['Tag', { tag: 'dt-tag' }],
  ['Pill', { pill: 'dt-pill', interactive: 'dt-pill', active: 'dt-pill-active' }],
  ['Switch', { switch: 'dt-switch', thumb: 'dt-switch-thumb' }],
  ['Modal', { root: 'dt-modal-root', mask: 'dt-modal-mask', dialog: 'dt-modal', content: 'dt-modal-content', header: 'dt-modal-header', title: 'dt-modal-title', close: 'dt-modal-close', description: 'dt-modal-description', body: 'dt-modal-body', footer: 'dt-modal-footer' }],
]
const output = copies.map(([name, classes]) => {
  const source = readFileSync(resolve(primitives, name + '.module.css'), 'utf8').replaceAll('\r\n', '\n')
  const css = source.replace(/\.([A-Za-z][\w-]*)/g, (match, key) => classes[key] ? '.' + classes[key] : match)
    .replaceAll('modalEnter', 'dt-native-modal-enter')
  return `/* DSH ui-primitives/src/${name}.module.css — copied with class names adapted. */\n${css.trim()}\n`
}).join('\n')
const target = resolve(root, 'src/client/native-controls.css')
const expected = '/* Generated by scripts/sync-native-ui-styles.mjs; do not restyle these primitives separately. */\n' + output
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== expected) throw new Error('Native control styles differ from the DSH source; run this script without --check to sync them.')
  console.log('Native control styles match all 6 DSH source stylesheets.')
} else writeFileSync(target, expected)
